"""Render descriptive measured tables without changing frozen classifications."""
import json,math,sys
from pathlib import Path
x=json.loads(Path(sys.argv[1]).read_text());s=x['summary'];ids=set(x['attempted_window_indices']);ws=[w for w in s['windows'] if w['index'] in ids]
lines=[]
def out(*v):lines.append(' '.join(str(z) for z in v))
def q(v,f):
 v=sorted(v);return f'{v[math.ceil(f*len(v))-1]:.3f}' if v else 'NA'
out('MEASURED DESCRIPTIVE TABLES — generated by report_tables.py from COMBINED.json')
out('Attempted windows:',len(ws),'of18; unrun:',x['unrun_window_indices'])
out('All tables below use ONLY attempted windows unless explicitly marked unrun.')
out('P=server slots; Q=exact correct AND on-time count. API-SLO ignores answer quality.')
out('All observed Q and quality counts are zero. Energy/Q is undefined in every window.')
out('Latency seconds: nearest-rank quantiles conditional on validated API completion.')
out('Component joules: gross CPU+GPU+ANE estimates, conditional interval-alignment bounds.')
out('Window7 remains serving-invalid; its observed counts/energy are retained and labeled.')
out('\nPER WINDOW')
out('index rate P rep N API failures unverified API-SLO quality Q unfinished90 valid criterion episodeJ[lo,hi]')
for w in ws:
 m=w['metrics'];e=w['energy']['intervals']['full_episode'];out(w['index'],w['rate'],w['parallel'],w['rep'],*(m[k] for k in ('planned_count','api_completed_count','recorded_failure_count','unverified_outcome_count','api_slo_count','quality_pass_count','quality_slo_count')),w['unfinished_offered_count']['90'],w['valid'],w['finite_window_screen']['passed'],f"[{e['lower_j']['combined']:.3f},{e['upper_j']['combined']:.3f}]" if e['valid'] else 'NA')
for i in x['unrun_window_indices']:out(i,'UNRUN — no requests and no energy; not a zero-throughput measurement')
out('\nOBSERVED RATE/P TOTALS; .3 has one repetition; .6 and1.2 have two.')
out('rate P repetitions N API API-SLO quality Q latency_n completion_p50 p95 first-content_p50 p95 episodeJ[lo,hi] serving_valid')
for rate in (.3,.6,1.2):
 for p in (1,2,4):
  a=[w for w in ws if w['rate']==rate and w['parallel']==p];r=[r for w in a for r in w['requests'] if r['api_completed']];e=[w['energy']['intervals']['full_episode'] for w in a]
  lo=sum(t['lower_j']['combined'] for t in e);hi=sum(t['upper_j']['combined'] for t in e)
  out(rate,p,','.join(str(w['rep']) for w in a),*(sum(w['metrics'][k] for w in a) for k in ('planned_count','api_completed_count','api_slo_count','quality_pass_count','quality_slo_count')),len(r),q([z['completion_latency_s'] for z in r],.5),q([z['completion_latency_s'] for z in r],.95),q([z['first_content_latency_s'] for z in r if z['first_content_latency_s'] is not None],.5),q([z['first_content_latency_s'] for z in r if z['first_content_latency_s'] is not None],.95),f'[{lo:.3f},{hi:.3f}]' if all(t['valid'] for t in e) else 'NA',all(w['valid'] for w in a))
out('\nMATCHED DIFFERENCES: P2-P1/P4-P1, same rate and trace repetition.')
out('rate rep contrast both-present serving-valid deltaAPI deltaAPI-SLO deltaQ deltaQ/N')
for c in s['matched_comparisons']:
 present=all(w['index'] in ids for w in s['windows'] if w['rate']==c['rate'] and w['rep']==c['rep'])
 d=c['difference'];out(c['rate'],c['rep'],c['contrast'],present,c['valid'],*(d[k] for k in ('api_completed_count','api_slo_count','quality_slo_count','quality_slo_fraction')) if present else ('NA','NA','NA','NA'))
out('\nOBSERVED STRATA (all attempted windows; includes invalidwindow7)')
out('dimension class N API failures API-SLO quality Q')
for dim in ('by_output_cap','by_input_rows','by_cross_class'):
 for k in sorted(ws[0][dim]):out(dim,k,*(sum(w[dim][k][v] for w in ws) for v in ('planned_count','api_completed_count','recorded_failure_count','api_slo_count','quality_pass_count','quality_slo_count')))
out('\nPER-WINDOW CAP STRATA')
out('index cap N API API-SLO Q')
for w in ws:
 for cap,m in sorted(w['by_output_cap'].items()):out(w['index'],cap,*(m[v] for v in ('planned_count','api_completed_count','api_slo_count','quality_slo_count')))
out('\nCOHORTS AND UNFINISHED PROXIES')
out('Unfinished offered includes unverified/dispatch boundary; known-dispatched is separate. Neither is server queue length.')
for w in ws:
 out('window',w['index'],'unfinished',json.dumps(w['unfinished_offered_count'],sort_keys=True),'known-dispatched',json.dumps(w['known_dispatched_unfinished_count'],sort_keys=True),'dispatchlag-max-seconds',w['maximum_dispatch_lag_s'])
 for name,m in w['offered_cohorts'].items():out(name,'N',m['planned_count'],'API',m['api_completed_count'],'API-SLO',m['api_slo_count'],'Q',m['quality_slo_count'])
out('\nENERGY PHASES; all domains in joules; time in seconds; no baseline subtraction.')
out('index phase seconds valid CPU[lo,hi] GPU[lo,hi] ANE[lo,hi] Combined[lo,hi]')
for w in ws:
 for phase,e in sorted(w['energy']['intervals'].items()):out(w['index'],phase,f"{e['duration_s']:.6f}",e['valid'],*(f"[{e['lower_j'][k]:.3f},{e['upper_j'][k]:.3f}]" if e['valid'] else 'NA' for k in ('cpu','gpu','ane','combined')))
out('Phase edge bounds overlap. Do not sum adjacent phase bounds to reconstruct full_episode.')
out('\nVALIDITY AND COMPLETENESS')
for w in ws:
 out('window',w['index'],'errors',json.dumps(w['validation_errors']),'failed conditions',','.join(k for k,v in w['finite_window_screen']['conditions'].items() if not v))
for c in s['rate_parallel_cells']:out(json.dumps(c,sort_keys=True))
out('No tested cell established the frozen finite-window criterion; unrun cells remain incomplete.')
out('Two observed repetitions at most; no population intervals, capacity, causal-energy or owner-pooling inference.')
Path(sys.argv[2]).write_text('\n'.join(lines)+'\n')
print('Wrote',sys.argv[2],len(lines),'lines')
