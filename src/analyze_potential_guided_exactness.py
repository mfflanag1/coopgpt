"""Test whether recoloring-dual level sets suffice for exactness repair.

The full endpoint LP gives every proper coalition its own tight core witness.
This diagnostic keeps only coalitions generated by level sets of the
recoloring-dual player potentials (and pairwise potential differences), plus
the circuit support and the two arms.  Success therefore gives a much more
structured two-level certificate and a candidate route to a direct theorem.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from fractions import Fraction as F
from pathlib import Path

import numpy as np
from scipy.optimize import linprog


def rat(value):
    return F(float(value)).limit_denominator(1_000_000)


def threshold_masks(vector):
    """All nontrivial weak and strict level sets of a rational vector."""
    n = len(vector)
    grand = (1 << n) - 1
    masks = set()
    for level in sorted(set(vector)):
        weak = sum(1 << i for i, value in enumerate(vector) if value >= level)
        strict = sum(1 << i for i, value in enumerate(vector) if value > level)
        if 0 < weak < grand:
            masks.add(weak)
        if 0 < strict < grand:
            masks.add(strict)
    return masks


MODE_SOURCES = {
    "full": frozenset({"potential", "difference", "support", "complement"}),
    "thresholds": frozenset({"potential", "difference"}),
    "potentials": frozenset({"potential"}),
    "arm-potentials": frozenset({"potential-1", "potential-2"}),
    "potential-0": frozenset({"potential-0"}),
    "potential-1": frozenset({"potential-1"}),
    "potential-2": frozenset({"potential-2"}),
    "differences": frozenset({"difference"}),
    "support": frozenset({"support"}),
    "support-complements": frozenset({"support", "complement"}),
    "threshold-support": frozenset({"potential", "difference", "support"}),
    "threshold-complements": frozenset({"potential", "difference", "complement"}),
}


def candidate_tights(n, A, B, detail, capacity_detail, mode="full"):
    grand = (1 << n) - 1
    sources = MODE_SOURCES[mode]
    supported = {A, B}
    for meta in detail["active_rows"]:
        if meta[0] == "core":
            supported.add(int(meta[2]))
    candidates = set(supported) if "support" in sources else set()
    if "complement" in sources:
        candidates.update(grand ^ coalition for coalition in supported)

    potentials = [
        [F(value) for value in vector]
        for vector in capacity_detail["dual_obstruction"]["game_player_potentials"]
    ]
    difference_vectors = []
    for left in range(3):
        for right in range(left + 1, 3):
            difference_vectors.append([
                potentials[left][i] - potentials[right][i] for i in range(n)
            ])
            difference_vectors.append([
                potentials[right][i] - potentials[left][i] for i in range(n)
            ])
    if "potential" in sources:
        for vector in potentials:
            candidates.update(threshold_masks(vector))
    for game, vector in enumerate(potentials):
        if f"potential-{game}" in sources:
            candidates.update(threshold_masks(vector))
    if "difference" in sources:
        for vector in difference_vectors:
            candidates.update(threshold_masks(vector))
    return tuple(sorted(mask for mask in candidates if 0 < mask < grand))


def analyze(
    circuit_payload,
    capacity_payload,
    circuit_index,
    candidate_mode="full",
    candidate_tights_override=None,
):
    n = int(circuit_payload["n"])
    A = int(circuit_payload["A_mask"])
    B = int(circuit_payload["B_mask"])
    detail = circuit_payload["circuits"][circuit_index - 1]
    capacity_detail = capacity_payload["circuits"][circuit_index - 1]
    assert capacity_detail["circuit_index"] == circuit_index
    assert capacity_detail["primal_exact"] and capacity_detail["dual_exact"]

    grand = (1 << n) - 1
    proper = tuple(range(1, grand))
    tights = (
        tuple(sorted(set(candidate_tights_override)))
        if candidate_tights_override is not None
        else candidate_tights(n, A, B, detail, capacity_detail, mode=candidate_mode)
    )
    if not tights:
        return {
            "status": "candidate witness family is empty",
            "n": n,
            "A_mask": A,
            "B_mask": B,
            "circuit_index": circuit_index,
            "candidate_mode": candidate_mode,
            "candidate_tights": [],
        }
    d_A = len(proper)
    d_B = d_A + 1
    witness_offset = d_B + 1
    tight_position = {tight: index for index, tight in enumerate(tights)}

    def worth_index(coalition):
        return coalition - 1

    def witness_index(game, tight, player):
        return witness_offset + ((game * len(tights) + tight_position[tight]) * n + player)

    def bump_index(game, coalition):
        if game == 1 and coalition == A:
            return d_A
        if game == 2 and coalition == B:
            return d_B
        return None

    variable_count = witness_offset + 3 * len(tights) * n
    objective = np.zeros(variable_count)
    efficiency_total = sum(F(value) for value in detail["efficiency_weights"])
    for meta, raw_weight in zip(detail["active_rows"], detail["circuit_weights"]):
        if meta[0] != "core":
            continue
        game, coalition = int(meta[1]), int(meta[2])
        weight = F(raw_weight)
        objective[worth_index(coalition)] -= float(weight)
        bump = bump_index(game, coalition)
        if bump is not None:
            objective[bump] -= float(weight)

    A_ub, b_ub, ub_meta = [], [], []
    A_eq, b_eq, eq_meta = [], [], []
    for game in range(3):
        for tight in tights:
            efficiency = np.zeros(variable_count)
            for player in range(n):
                efficiency[witness_index(game, tight, player)] = 1
            A_eq.append(efficiency)
            b_eq.append(1)
            eq_meta.append((game, tight, "efficiency"))

            for coalition in proper:
                core = np.zeros(variable_count)
                core[worth_index(coalition)] = 1
                bump = bump_index(game, coalition)
                if bump is not None:
                    core[bump] = 1
                for player in range(n):
                    if coalition >> player & 1:
                        core[witness_index(game, tight, player)] = -1
                A_ub.append(core)
                b_ub.append(0)
                ub_meta.append((game, tight, coalition))

            tightness = np.zeros(variable_count)
            for player in range(n):
                if tight >> player & 1:
                    tightness[witness_index(game, tight, player)] = 1
            tightness[worth_index(tight)] = -1
            bump = bump_index(game, tight)
            if bump is not None:
                tightness[bump] = -1
            A_eq.append(tightness)
            b_eq.append(0)
            eq_meta.append((game, tight, "tightness"))

    bounds = [(None, None)] * variable_count
    bounds[d_A] = (0, None)
    bounds[d_B] = (0, None)
    result = linprog(
        objective, A_ub=np.asarray(A_ub), b_ub=np.asarray(b_ub),
        A_eq=np.asarray(A_eq), b_eq=np.asarray(b_eq),
        bounds=bounds, method="highs",
    )
    if not result.success:
        return {
            "status": "potential-guided witnesses do not certify the bound",
            "solver_status": result.message,
            "n": n,
            "A_mask": A,
            "B_mask": B,
            "circuit_index": circuit_index,
            "candidate_mode": candidate_mode,
            "candidate_tights": list(tights),
        }

    solution = [rat(value) for value in result.x]
    primal_exact = all(
        sum(F(int(a)) * x for a, x in zip(row, solution) if a) <= F(int(rhs))
        for row, rhs in zip(A_ub, b_ub)
    ) and all(
        sum(F(int(a)) * x for a, x in zip(row, solution) if a) == F(int(rhs))
        for row, rhs in zip(A_eq, b_eq)
    ) and solution[d_A] >= 0 and solution[d_B] >= 0

    y = [rat(value) for value in result.ineqlin.marginals]
    beta = [rat(value) for value in result.eqlin.marginals]
    lower = [rat(value) for value in result.lower.marginals]
    combined = [F(0)] * variable_count
    for multiplier, row in zip(y, A_ub):
        for column, coefficient in enumerate(row):
            if coefficient:
                combined[column] += multiplier * F(int(coefficient))
    for multiplier, row in zip(beta, A_eq):
        for column, coefficient in enumerate(row):
            if coefficient:
                combined[column] += multiplier * F(int(coefficient))
    for column, multiplier in enumerate(lower):
        combined[column] += multiplier
    exact_objective = [rat(value) for value in objective]
    dual_bound = sum(multiplier * F(int(rhs)) for multiplier, rhs in zip(beta, b_eq))
    dual_exact = (
        all(value <= 0 for value in y)
        and all(value >= 0 for value in lower)
        and all(not value or index in (d_A, d_B) for index, value in enumerate(lower))
        and combined == exact_objective
        and dual_bound == -efficiency_total
    )

    collections = defaultdict(dict)
    for multiplier, (game, tight, coalition) in zip(y, ub_meta):
        if multiplier:
            collections[(game, tight)][coalition] = -multiplier
    equality = {
        meta: multiplier for meta, multiplier in zip(eq_meta, beta) if multiplier
    }
    blocks = []
    for (game, tight), collection in sorted(collections.items()):
        alpha = -equality.get((game, tight, "efficiency"), F(0))
        delta = -equality.get((game, tight, "tightness"), F(0))
        coverage = [
            sum((weight for coalition, weight in collection.items()
                 if coalition >> player & 1), F(0))
            for player in range(n)
        ]
        expected = [alpha + (delta if tight >> player & 1 else 0)
                    for player in range(n)]
        assert coverage == expected
        blocks.append({
            "game": game,
            "tight_coalition": tight,
            "alpha": str(alpha),
            "delta": str(delta),
            "collection": {str(S): str(w) for S, w in sorted(collection.items())},
        })

    supported = -sum(F(int(a)) * x for a, x in zip(objective, solution) if a)
    margin = efficiency_total - supported
    return {
        "status": (
            "POTENTIAL-GUIDED EXACTNESS CERTIFICATE VERIFIED"
            if primal_exact and dual_exact and margin == 0
            else "floating candidate failed exact verification"
        ),
        "n": n,
        "A_mask": A,
        "B_mask": B,
        "circuit_index": circuit_index,
        "candidate_mode": candidate_mode,
        "capacity": capacity_detail["capacity"],
        "candidate_tight_count": len(tights),
        "candidate_tights": list(tights),
        "block_count": len(blocks),
        "used_tight_count": len({block["tight_coalition"] for block in blocks}),
        "used_tights": sorted({block["tight_coalition"] for block in blocks}),
        "circuit_margin": str(margin),
        "primal_exact": primal_exact,
        "dual_exact": dual_exact,
        "dual_bound": str(dual_bound),
        "blocks": blocks,
    }


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("circuit_payload", type=Path)
    parser.add_argument("capacity_payload", type=Path)
    parser.add_argument("--circuit-index", type=int, required=True)
    parser.add_argument(
        "--candidate-mode", choices=tuple(MODE_SOURCES), default="full"
    )
    parser.add_argument("--output", type=Path)
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    payload = analyze(
        json.loads(args.circuit_payload.read_text()),
        json.loads(args.capacity_payload.read_text()),
        args.circuit_index,
        candidate_mode=args.candidate_mode,
    )
    rendered = json.dumps(payload, indent=2) + "\n"
    if args.output:
        args.output.write_text(rendered)
    else:
        print(rendered, end="")
