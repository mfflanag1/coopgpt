"""Exact phase diagram for additive perturbations of the Paper 2 base game.

The base game is generated by

    U = (0,1,0,1,2,0),  V = (1,0,1,0,0,2),
    w(S) = min(U(S), V(S)).

For an additive vector c, v_c = w + c.  Adding the same scalar to every
coordinate translates every procedural claim by that scalar and leaves the
admissible coalitions unchanged.  We therefore normalize c_6 = 0 and enumerate
an integer box for the other five coordinates.  All arithmetic is rational.

This is a classification on the stated lattice box, not a claim that the
continuous parameter space has been exhausted.  The trace signatures it emits
are intended as input to the symbolic chamber analysis.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from fractions import Fraction as F
from itertools import product
from pathlib import Path

from tugame import Game, members


U = (0, 1, 0, 1, 2, 0)
V = (1, 0, 1, 0, 0, 2)


def additive_game(c: tuple[int, ...]) -> Game:
    n = len(U)
    N = (1 << n) - 1
    values = [F(0)] * (1 << n)
    for S in range(1, N + 1):
        us = sum(U[i] for i in members(S, n))
        vs = sum(V[i] for i in members(S, n))
        cs = sum(c[i] for i in members(S, n))
        values[S] = min(us, vs) + cs
    return Game(n, values)


def procedure_trace(game: Game):
    """Return exact claims, ES flag, and a compact round signature."""
    n, N, v = game.n, game.N, game.v
    fixed: dict[int, F] = {}
    rounds = []
    final_A = []

    for _ in range(n + 1):
        if len(fixed) == n:
            break
        chi = {}
        maxima = {i: None for i in range(n)}
        for S in range(1, N + 1):
            mem = members(S, n)
            free = [i for i in mem if i not in fixed]
            fixed_sum = sum((fixed[i] for i in mem if i in fixed), F(0))
            share = ((v[S] - fixed_sum) / len(free)) if free else None
            row = {i: (fixed[i] if i in fixed else share) for i in mem}
            chi[S] = row
            for i in mem:
                if maxima[i] is None or row[i] > maxima[i]:
                    maxima[i] = row[i]

        A = []
        for S in range(1, N + 1):
            mem = members(S, n)
            if sum((chi[S][i] for i in mem), F(0)) != v[S]:
                continue
            if all(chi[S][i] == maxima[i] for i in mem):
                A.append(S)

        before = set(fixed)
        for S in A:
            for i in members(S, n):
                if i not in fixed:
                    fixed[i] = maxima[i]
        new_players = tuple(sorted(set(fixed) - before))
        rounds.append((tuple(A), new_players))
        final_A = A

    claims = tuple(fixed[i] for i in range(n))
    return claims, N in final_A, tuple(rounds)


def mask_name(S: int, n: int = 6) -> str:
    return "".join(str(i + 1) for i in range(n) if S >> i & 1) or "0"


def frac_name(x: F) -> str:
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def signature_name(signature) -> str:
    pieces = []
    for coalitions, players in signature:
        a = ",".join(mask_name(S) for S in coalitions)
        p = "".join(str(i + 1) for i in players)
        pieces.append(f"A=[{a}];P={p}")
    return " | ".join(pieces)


def analyze(radius: int):
    records = []
    sig_counts = Counter()
    sig_examples = {}
    coarse_counts = Counter()
    coarse_examples = {}
    es_counts = Counter()
    slack_counts = Counter()
    nones_by_support = Counter()
    nones_by_order = Counter()

    for first_five in product(range(-radius, radius + 1), repeat=5):
        c = tuple(first_five) + (0,)
        game = additive_game(c)
        claims, is_es, signature = procedure_trace(game)
        slack = sum(claims, F(0)) - game.v[game.N]
        key = signature_name(signature)
        coarse_key = " / ".join(
            "".join(str(i + 1) for i in players) for _, players in signature
        )
        sig_counts[key] += 1
        sig_examples.setdefault(key, c)
        coarse_counts[(is_es, coarse_key)] += 1
        coarse_examples.setdefault((is_es, coarse_key), c)
        es_counts[is_es] += 1
        slack_counts[frac_name(slack)] += 1
        if not is_es:
            support = tuple(i + 1 for i, value in enumerate(c) if value != 0)
            nones_by_support[support] += 1
            order = tuple(sorted(range(6), key=lambda i: (c[i], i)))
            nones_by_order[order] += 1
        records.append((c, claims, is_es, slack, key))

    signature_rows = []
    for key, count in sig_counts.most_common():
        ex = sig_examples[key]
        ex_record = next(row for row in records if row[0] == ex)
        signature_rows.append(
            {
                "count": count,
                "example_c": list(ex),
                "example_claims": [frac_name(x) for x in ex_record[1]],
                "example_is_ES": ex_record[2],
                "example_slack": frac_name(ex_record[3]),
                "trace": key,
            }
        )

    return {
        "normalization": "c_6 = 0 (uniform additive shifts suppressed)",
        "radius": radius,
        "total": len(records),
        "ES": es_counts[True],
        "non_ES": es_counts[False],
        "distinct_trace_signatures": len(sig_counts),
        "slack_distribution": dict(sorted(slack_counts.items())),
        "trace_signatures_top_40": signature_rows[:40],
        "coarse_stratum_signatures": [
            {
                "count": count,
                "is_ES": key[0],
                "newly_fixed_strata": key[1],
                "example_c": list(coarse_examples[key]),
            }
            for key, count in coarse_counts.most_common()
        ],
        "most_common_non_ES_supports": [
            {"support": list(k), "count": v}
            for k, v in nones_by_support.most_common(20)
        ],
        "most_common_non_ES_coordinate_orders": [
            {"zero_based_order": list(k), "count": v}
            for k, v in nones_by_order.most_common(20)
        ],
    }


def write_markdown(report, path: Path):
    lines = [
        "# Exact additive-perturbation lattice classification",
        "",
        f"Normalization: `{report['normalization']}`.",
        f"Box: each of `c_1,...,c_5` lies in `[-{report['radius']},{report['radius']}]`.",
        "",
        f"- Total shifts: {report['total']}",
        f"- Egalitarian stable: {report['ES']}",
        f"- Not egalitarian stable: {report['non_ES']}",
        f"- Distinct procedural traces: {report['distinct_trace_signatures']}",
        "",
        "This is an exact finite-lattice classification, not yet a continuous chamber theorem.",
        "",
        "## Procedural trace signatures",
        "",
    ]
    lines.extend(["## Newly-fixed stratum signatures", ""])
    for row in report["coarse_stratum_signatures"]:
        lines.append(
            f"- count {row['count']}; ES={row['is_ES']}; strata "
            f"`{row['newly_fixed_strata']}`; example `c={row['example_c']}`"
        )
    lines.extend(["", "## Forty most common full procedural traces", ""])
    for index, row in enumerate(report["trace_signatures_top_40"], 1):
        lines.extend(
            [
                f"### {index}. count {row['count']}; ES={row['example_is_ES']}",
                "",
                f"Example `c={row['example_c']}`; claims `{row['example_claims']}`; "
                f"slack `{row['example_slack']}`.",
                "",
                f"Trace: `{row['trace']}`",
                "",
            ]
        )
    path.write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--radius", type=int, default=2)
    parser.add_argument(
        "--json",
        type=Path,
        default=Path("results/additive_perturbation_classification.json"),
    )
    parser.add_argument(
        "--markdown",
        type=Path,
        default=Path("results/additive_perturbation_classification.md"),
    )
    args = parser.parse_args()
    report = analyze(args.radius)
    args.json.write_text(json.dumps(report, indent=2) + "\n")
    write_markdown(report, args.markdown)
    print(
        f"classified {report['total']} shifts: ES={report['ES']}, "
        f"non-ES={report['non_ES']}, traces={report['distinct_trace_signatures']}"
    )


if __name__ == "__main__":
    main()
