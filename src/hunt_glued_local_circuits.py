"""Target nonexclusive capacity failure by exact local-circuit gluing.

This is a factorized adversarial search for the n=6 disjoint shape
|A|=3, |B|=2, |R|=1.  It enumerates nullity-one positive circuits in the
three game blocks independently, matches their shared monotonicity weights,
and thereby obtains global nullity-one positive circuits without searching
random global bases.

The current pattern puts an extra B-copy in the root block and an extra
A-copy in the second leaf.  All product-forbidden gluings are screened.
Exact reduced capacities are then computed for the most severe scalar gaps
and for one representative of every distinct arm-ratio pair.
"""
from __future__ import annotations

import argparse
import itertools
import json
import math
from collections import Counter
from fractions import Fraction as F
from pathlib import Path

import numpy as np
import sympy as sp

from analyze_two_color_box_capacity import analyze, circuit_data
from search_both_sensitive_circuits import eliminated_matrix


N = 6
A = 0b000111
B = 0b011000
A_PLAYER = 0
B_PLAYER = 3


def primitive_positive_kernel(block):
    """Exact primitive positive generator of a nullity-one kernel.

    The caller has already certified rank ``width - 1`` modulo 61.  A
    full-rank row restriction therefore has a kernel generated by its signed
    maximal minors.  The final multiplication checks the cofactor vector
    against every row of the original integer block.
    """
    height, width = block.shape
    rank = width - 1
    for rows in itertools.combinations(range(height), rank):
        restricted = [[int(block[row, column]) for column in range(width)]
                      for row in rows]
        integers = [
            (-1) ** column * determinant_bareiss([
                row[:column] + row[column + 1:] for row in restricted
            ])
            for column in range(width)
        ]
        if not any(integers):
            continue
        assert all(
            sum(int(block[row, column]) * integers[column]
                for column in range(width)) == 0
            for row in range(height)
        )
        if all(value < 0 for value in integers):
            integers = [-value for value in integers]
        if not all(value > 0 for value in integers):
            return None
        divisor = abs(math.gcd(*integers))
        return tuple(value // divisor for value in integers)
    raise AssertionError("certified rank has no nonzero maximal minor")


def determinant_bareiss(square):
    """Exact determinant of a small integer matrix by Bareiss elimination."""
    size = len(square)
    if size == 0:
        return 1
    matrix = [list(map(int, row)) for row in square]
    sign = 1
    previous = 1
    for pivot_index in range(size - 1):
        if matrix[pivot_index][pivot_index] == 0:
            swap = next(
                (row for row in range(pivot_index + 1, size)
                 if matrix[row][pivot_index] != 0),
                None,
            )
            if swap is None:
                return 0
            matrix[pivot_index], matrix[swap] = (
                matrix[swap], matrix[pivot_index]
            )
            sign = -sign
        pivot = matrix[pivot_index][pivot_index]
        for row in range(pivot_index + 1, size):
            for column in range(pivot_index + 1, size):
                numerator = (
                    matrix[row][column] * pivot
                    - matrix[row][pivot_index]
                    * matrix[pivot_index][column]
                )
                assert numerator % previous == 0
                matrix[row][column] = numerator // previous
            matrix[row][pivot_index] = 0
        previous = pivot
    return sign * matrix[-1][-1]


def rank_mod_prime(block, prime=61):
    """Exact rational rank for these {-1,0,1} matrices.

    Hadamard bounds every square minor by ``5**(5/2) < 56``.  Hence a
    minor is nonzero over the rationals exactly when it is nonzero modulo 61.
    """
    raw = block.tolist() if hasattr(block, "tolist") else block
    matrix = [
        [int(value) % prime for value in row]
        for row in raw
    ]
    height = len(matrix)
    width = len(matrix[0]) if matrix else 0
    pivot_row = 0
    for column in range(width):
        pivot = next(
            (row for row in range(pivot_row, height)
             if matrix[row][column]),
            None,
        )
        if pivot is None:
            continue
        matrix[pivot_row], matrix[pivot] = matrix[pivot], matrix[pivot_row]
        inverse = pow(matrix[pivot_row][column], -1, prime)
        matrix[pivot_row] = [
            value * inverse % prime for value in matrix[pivot_row]
        ]
        for row in range(height):
            if row == pivot_row or not matrix[row][column]:
                continue
            scale = matrix[row][column]
            matrix[row] = [
                (value - scale * pivot_value) % prime
                for value, pivot_value in zip(
                    matrix[row], matrix[pivot_row]
                )
            ]
        pivot_row += 1
        if pivot_row == height:
            break
    return pivot_row


def enumerate_local(matrix, rowmeta, game, mandatory, players=N):
    """Enumerate local positive circuits for a specified player count."""
    width = players - 1
    block = matrix[game * width:(game + 1) * width, :].astype(int)
    core = [
        index
        for index, meta in enumerate(rowmeta)
        if meta[0] == "core" and meta[1] == game
    ]
    pool = [index for index in core if index not in mandatory]
    circuits = []
    for size in range(len(mandatory), width + 2):
        for extra in itertools.combinations(pool, size - len(mandatory)):
            support = tuple(mandatory) + extra
            restricted = block[:, support]
            if rank_mod_prime(restricted) != size - 1:
                continue
            weights = primitive_positive_kernel(restricted)
            if weights is not None:
                circuits.append((support, weights))
    return circuits


def coefficient(circuit, index):
    return F(dict(zip(*circuit)).get(index, 0))


def glue(root, leaf_A, leaf_B, mono_A, mono_B):
    root_support, root_weights = root
    weights = {
        index: F(value)
        for index, value in zip(root_support, root_weights)
    }
    scale_A = weights[mono_A] / coefficient(leaf_A, mono_A)
    scale_B = weights[mono_B] / coefficient(leaf_B, mono_B)
    for circuit, scale in ((leaf_A, scale_A), (leaf_B, scale_B)):
        for index, value in zip(*circuit):
            if index in (mono_A, mono_B):
                continue
            weights[index] = scale * value

    denominator = 1
    for value in weights.values():
        denominator = math.lcm(denominator, value.denominator)
    integers = {
        index: int(value * denominator) for index, value in weights.items()
    }
    divisor = abs(math.gcd(*integers.values()))
    integers = {index: value // divisor for index, value in integers.items()}
    support = tuple(sorted(integers))
    return support, tuple(integers[index] for index in support)


def candidate_record(rowmeta, support, weights):
    payload = {
        "n": N,
        "A_mask": A,
        "B_mask": B,
        "circuits": [{
            "active_rows": [list(rowmeta[index]) for index in support],
            "circuit_weights": list(weights),
        }],
    }
    _n, _A, _B, aggregate, x, y = circuit_data(payload, 1)
    U = aggregate[A] - x
    V = aggregate[B] - y
    ratio_A = (x + U) / x
    ratio_B = (y + V) / y
    scalar_capacity = 1 / (1 / ratio_A + 1 / ratio_B)
    return {
        "payload": payload,
        "support": support,
        "weights": weights,
        "x": x,
        "y": y,
        "U": U,
        "V": V,
        "product_gap": U * V - x * y,
        "ratio_A": ratio_A,
        "ratio_B": ratio_B,
        "scalar_capacity": scalar_capacity,
        "aggregate": aggregate,
    }


def aggregate_support_structure(aggregate):
    support = tuple(sorted(coalition for coalition, weight in aggregate.items() if weight))
    incidence = [[1] * N]
    incidence.extend([
        [int(coalition >> player & 1) for player in range(N)]
        for coalition in support
    ])
    rank = int(sp.Matrix(incidence).rank())
    signatures = {
        tuple(int(coalition >> player & 1) for coalition in support)
        for player in range(N)
    }
    nullity = N - rank
    twin_nullity = N - len(signatures)
    return {
        "support_size": len(support),
        "support_nullity": nullity,
        "twin_swap_nullity": twin_nullity,
        "twin_generated": nullity == twin_nullity,
    }


def render_candidate(candidate, capacity):
    rendered = {
        "ratio_A": str(candidate["ratio_A"]),
        "ratio_B": str(candidate["ratio_B"]),
        "scalar_capacity": str(candidate["scalar_capacity"]),
        "arm_masses": {
            key: str(candidate[key]) for key in ("x", "y", "U", "V")
        },
        "product_gap": str(candidate["product_gap"]),
        "capacity": capacity,
        "active_rows": candidate["payload"]["circuits"][0]["active_rows"],
        "circuit_weights": list(candidate["weights"]),
    }
    if "local_indices" in candidate:
        rendered["local_indices"] = dict(candidate["local_indices"])
    return rendered


def primitive_projective(values):
    """Return the primitive integer representative of a rational ray."""
    values = tuple(F(value) for value in values)
    denominator = 1
    for value in values:
        denominator = math.lcm(denominator, value.denominator)
    integers = [int(value * denominator) for value in values]
    divisor = abs(math.gcd(*integers))
    if divisor:
        integers = [value // divisor for value in integers]
    for value in integers:
        if value:
            if value < 0:
                integers = [-entry for entry in integers]
            break
    return tuple(integers)


def weak_order_pattern(values):
    """Encode coordinate level sets by consecutive ranks, lowest first."""
    values = tuple(F(value) for value in values)
    levels = {value: rank for rank, value in enumerate(sorted(set(values)))}
    return tuple(levels[value] for value in values)


def hunt(max_checks, structural_only=False, audit_witness=None):
    matrix, _inequalities, _equalities, rowmeta = eliminated_matrix(N, A, B)
    mono_A = rowmeta.index(("mono", 0, 1, A_PLAYER, A))
    mono_B = rowmeta.index(("mono", 0, 2, B_PLAYER, B))
    root_B = rowmeta.index(("core", 0, B))
    leaf_A = rowmeta.index(("core", 1, A))
    crossed_A = rowmeta.index(("core", 2, A))
    leaf_B = rowmeta.index(("core", 2, B))

    roots = enumerate_local(matrix, rowmeta, 0, (mono_A, mono_B, root_B))
    first_leaves = enumerate_local(matrix, rowmeta, 1, (mono_A, leaf_A))
    second_leaves = enumerate_local(
        matrix, rowmeta, 2, (mono_B, crossed_A, leaf_B)
    )
    second_leaves = [
        circuit
        for circuit in second_leaves
        if coefficient(circuit, crossed_A) < coefficient(circuit, leaf_B)
    ]

    candidates = {}
    for root_index, root in enumerate(roots, 1):
        for first_index, first in enumerate(first_leaves, 1):
            for second_index, second in enumerate(second_leaves, 1):
                support, weights = glue(
                    root, first, second, mono_A, mono_B
                )
                signature = (support, weights)
                if signature in candidates:
                    continue
                record = candidate_record(rowmeta, support, weights)
                if record["product_gap"] < 0:
                    record["local_indices"] = {
                        "root": root_index,
                        "first_leaf": first_index,
                        "second_leaf": second_index,
                    }
                    candidates[signature] = record

    ordered = sorted(
        candidates.values(),
        key=lambda item: (
            item["scalar_capacity"],
            item["support"],
            item["weights"],
        ),
    )
    structure_cache = {}
    circuit_structures = []
    aggregate_coalition_universe = set()
    for candidate in ordered:
        support_key = tuple(sorted(candidate["aggregate"]))
        aggregate_coalition_universe.update(support_key)
        if support_key not in structure_cache:
            structure_cache[support_key] = aggregate_support_structure(
                candidate["aggregate"]
            )
        circuit_structures.append(structure_cache[support_key])
    structural_audit = {
        "distinct_aggregate_supports": len(structure_cache),
        "nontrivial_support_nullspace_circuits": sum(
            item["support_nullity"] > 0 for item in circuit_structures
        ),
        "non_twin_support_nullspace_circuits": sum(
            not item["twin_generated"] for item in circuit_structures
        ),
        "maximum_support_nullity": max(
            (item["support_nullity"] for item in circuit_structures), default=0
        ),
        "all_support_nullspaces_twin_generated": all(
            item["twin_generated"] for item in circuit_structures
        ),
        "aggregate_coalition_universe": sorted(
            aggregate_coalition_universe
        ),
    }
    if structural_only:
        return {
            "status": "exact aggregate-support audit of product-forbidden gluings",
            "geometry": {
                "n": N,
                "A_mask": A,
                "B_mask": B,
                "A_monotonicity_player_0indexed": A_PLAYER,
                "B_monotonicity_player_0indexed": B_PLAYER,
                "pattern": "root contains B; second leaf contains A and B",
            },
            "local_circuit_counts": {
                "root": len(roots),
                "first_leaf": len(first_leaves),
                "product_violating_second_leaf": len(second_leaves),
            },
            "distinct_product_forbidden_gluings": len(candidates),
            "support_structure": structural_audit,
        }
    if audit_witness is not None:
        capacities = []
        failures = []
        minimum_records = []
        minimum_capacity = None
        minimum_arm_mass_histogram = Counter()
        minimum_dual_ray_histogram = Counter()
        minimum_local_triples = []
        capacity_histogram = Counter()
        dual_ray_histogram = Counter()
        dual_ray_capacity_histogram = Counter()
        potential_order_histogram = Counter()
        primal_profile_histogram = Counter()
        local_ray_capacity_histograms = {
            "root": Counter(),
            "first_leaf": Counter(),
            "second_leaf": Counter(),
        }
        for candidate in ordered:
            fixed = analyze(candidate["payload"], 1, audit_witness)
            assert fixed["primal_exact"] and fixed["dual_exact"]
            capacity = F(fixed["capacity"])
            capacities.append(capacity)
            capacity_histogram[capacity] += 1
            retention = fixed["retention_duals"]
            gamma = tuple(F(value) for value in fixed["player_potential"])
            dual_ray = primitive_projective((
                -F(retention["A"]), -F(retention["B"]), *gamma,
            ))
            dual_ray_histogram[dual_ray] += 1
            dual_ray_capacity_histogram[(dual_ray, capacity)] += 1
            potential_order_histogram[weak_order_pattern(gamma)] += 1
            primal_profile_histogram[(
                F(fixed["alpha"]), F(fixed["delta"]),
                len(fixed["subcollection"]),
            )] += 1
            for label, index in candidate["local_indices"].items():
                local_ray_capacity_histograms[label][(index, capacity)] += 1
            rendered = render_candidate(candidate, fixed)
            if minimum_capacity is None or capacity < minimum_capacity:
                minimum_capacity = capacity
                minimum_records = [rendered]
                minimum_arm_mass_histogram = Counter({
                    tuple(candidate[key] for key in ("x", "y", "U", "V")): 1
                })
                minimum_dual_ray_histogram = Counter({dual_ray: 1})
                minimum_local_triples = [dict(candidate["local_indices"])]
            elif capacity == minimum_capacity:
                if len(minimum_records) < 10:
                    minimum_records.append(rendered)
                minimum_arm_mass_histogram[
                    tuple(candidate[key] for key in ("x", "y", "U", "V"))
                ] += 1
                minimum_dual_ray_histogram[dual_ray] += 1
                minimum_local_triples.append(dict(candidate["local_indices"]))
            if capacity < 1 and len(failures) < 20:
                failures.append(rendered)
        return {
            "status": "exact fixed-witness audit of product-forbidden gluings",
            "geometry": {
                "n": N,
                "A_mask": A,
                "B_mask": B,
                "A_monotonicity_player_0indexed": A_PLAYER,
                "B_monotonicity_player_0indexed": B_PLAYER,
                "pattern": "root contains B; second leaf contains A and B",
            },
            "fixed_witness": audit_witness,
            "distinct_product_forbidden_gluings": len(candidates),
            "capacities_checked": len(capacities),
            "minimum_fixed_witness_capacity": (
                str(minimum_capacity) if minimum_capacity is not None else None
            ),
            "capacity_below_one_count": sum(value < 1 for value in capacities),
            "capacity_equal_one_count": sum(value == 1 for value in capacities),
            "capacity_above_one_count": sum(value > 1 for value in capacities),
            "support_structure": structural_audit,
            "capacity_histogram": {
                str(value): count
                for value, count in sorted(capacity_histogram.items())
            },
            "dual_template_summary": {
                "distinct_projective_rays": len(dual_ray_histogram),
                "most_common_projective_rays": [
                    {
                        "ray": list(ray),
                        "count": count,
                    }
                    for ray, count in dual_ray_histogram.most_common(25)
                ],
                "projective_ray_capacity_table": [
                    {
                        "ray": list(ray),
                        "capacity": str(capacity),
                        "count": count,
                    }
                    for (ray, capacity), count in sorted(
                        dual_ray_capacity_histogram.items(),
                        key=lambda item: (
                            item[0][1], item[0][0],
                        ),
                    )
                ],
                "distinct_potential_weak_orders": len(
                    potential_order_histogram
                ),
                "potential_weak_orders": [
                    {
                        "pattern": list(pattern),
                        "count": count,
                    }
                    for pattern, count in potential_order_histogram.most_common()
                ],
                "distinct_primal_profiles": len(primal_profile_histogram),
                "most_common_primal_profiles": [
                    {
                        "alpha": str(profile[0]),
                        "delta": str(profile[1]),
                        "subcollection_support_size": profile[2],
                        "count": count,
                    }
                    for profile, count in primal_profile_histogram.most_common(25)
                ],
                "local_ray_capacity_tables": {
                    label: [
                        {
                            "local_index": index,
                            "capacity": str(capacity),
                            "count": count,
                        }
                        for (index, capacity), count in sorted(
                            histogram.items(),
                            key=lambda item: (item[0][0], item[0][1]),
                        )
                    ]
                    for label, histogram in local_ray_capacity_histograms.items()
                },
            },
            "minimum_frontier": {
                "record_count": sum(minimum_arm_mass_histogram.values()),
                "arm_mass_histogram": [
                    {
                        "arm_masses": {
                            key: str(value)
                            for key, value in zip(
                                ("x", "y", "U", "V"), masses
                            )
                        },
                        "count": count,
                    }
                    for masses, count in sorted(
                        minimum_arm_mass_histogram.items()
                    )
                ],
                "dual_rays": [
                    {"ray": list(ray), "count": count}
                    for ray, count in sorted(
                        minimum_dual_ray_histogram.items()
                    )
                ],
                "local_triples": minimum_local_triples,
            },
            "minimum_capacity_records": minimum_records,
            "failure_records": failures,
        }
    selected = ordered[:max_checks]
    ratio_representatives = {}
    for candidate in ordered:
        key = (candidate["ratio_A"], candidate["ratio_B"])
        ratio_representatives.setdefault(key, candidate)
    selected_signatures = {
        (item["support"], item["weights"]) for item in selected
    }
    for candidate in ratio_representatives.values():
        signature = (candidate["support"], candidate["weights"])
        if signature not in selected_signatures:
            selected.append(candidate)
            selected_signatures.add(signature)

    checked = []
    deficient = []
    for candidate in selected:
        capacity = analyze(candidate["payload"], 1)
        assert capacity["primal_exact"] and capacity["dual_exact"]
        rendered = render_candidate(candidate, capacity)
        checked.append(rendered)
        if F(capacity["capacity"]) < 1:
            extrema = {}
            for witness in sorted({
                capacity["maximum_set"], capacity["minimum_set"]
            }):
                fixed = analyze(candidate["payload"], 1, witness)
                assert fixed["primal_exact"] and fixed["dual_exact"]
                extrema[str(witness)] = fixed
            rendered["extreme_witness_capacities"] = extrema
            rendered["both_extremes_repair_full_bumps"] = all(
                F(item["capacity"]) >= 1 for item in extrema.values()
            )
            deficient.append(rendered)

    checked.sort(
        key=lambda item: (
            F(item["capacity"]["capacity"]),
            F(item["scalar_capacity"]),
        )
    )
    return {
        "status": (
            "DEFICIENT NONEXCLUSIVE GLUED CIRCUIT FOUND"
            if deficient
            else "no deficient circuit in selected exact glued screen"
        ),
        "n": N,
        "A_mask": A,
        "B_mask": B,
        "geometry": {
            "n": N,
            "A_mask": A,
            "B_mask": B,
            "A_monotonicity_player_0indexed": A_PLAYER,
            "B_monotonicity_player_0indexed": B_PLAYER,
            "pattern": "root contains B; second leaf contains A and B",
        },
        "local_circuit_counts": {
            "root": len(roots),
            "first_leaf": len(first_leaves),
            "product_violating_second_leaf": len(second_leaves),
        },
        "distinct_product_forbidden_gluings": len(candidates),
        "support_structure": structural_audit,
        "distinct_arm_ratio_pairs": len(ratio_representatives),
        "capacities_checked": len(checked),
        "deficient_count": len(deficient),
        "deficient_with_both_extremes_repairing": sum(
            item["both_extremes_repair_full_bumps"] for item in deficient
        ),
        "minimum_checked_capacity": (
            checked[0]["capacity"]["capacity"] if checked else None
        ),
        "lowest_capacity_records": checked[:10],
        "deficient_records": deficient,
    }


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-checks", type=int, default=5000)
    parser.add_argument("--structural-only", action="store_true")
    parser.add_argument("--audit-witness", type=lambda value: int(value, 0))
    parser.add_argument("--output", type=Path)
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    rendered = json.dumps(
        hunt(
            args.max_checks,
            structural_only=args.structural_only,
            audit_witness=args.audit_witness,
        ),
        indent=2,
    ) + "\n"
    if args.output:
        args.output.write_text(rendered)
    else:
        print(rendered, end="")
