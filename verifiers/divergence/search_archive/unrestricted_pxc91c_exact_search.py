def csum(point, mask):
    return sum((point[i] for i in range(len(point)) if mask >> i & 1), F(0))


def lower_envelope(constraints, n, total):
    aub, bub = [], []
    for mask, bound in constraints.items():
        if bound == 0:
            continue
        aub.append([-F((mask >> i) & 1) for i in range(n)]); bub.append(-bound)
    for i in range(n):
        row = [F(0)] * n; row[i] = -1
        aub.append(row); bub.append(F(0))
    answer = []
    for mask in range(1 << n):
        objective = [F((mask >> i) & 1) for i in range(n)]
        status, value, _point = exact_linprog(
            objective, aub, bub, [[F(1)] * n], [total]
        )
        if status != "optimal":
            raise RuntimeError(("coalition LP failed", n, mask, status))
        answer.append(value)
    return tuple(answer)


def selector_from_constraints(constraints, n, total, mode):
    """Exact staged leximin/leximax selector of a TU-game core.

    This intentionally uses only the solver-free rational simplex.  It is
    independent of the certified/floating selector stack used by several
    older discovery drivers.
    """
    pinned = {}
    free = set(range(n))

    def base(width):
        aub, bub, aeq, beq = [], [], [], []
        row = [F(1)] * n + [F(0)] * (width - n)
        aeq.append(row); beq.append(total)
        for mask, bound in constraints.items():
            if mask == (1 << n) - 1 or bound == 0:
                continue
            row = [-F((mask >> i) & 1) for i in range(n)]
            row += [F(0)] * (width - n)
            aub.append(row); bub.append(-bound)
        for player in range(n):
            row = [F(0)] * width; row[player] = F(-1)
            aub.append(row); bub.append(F(0))
        for player, value in pinned.items():
            row = [F(0)] * width; row[player] = F(1)
            aeq.append(row); beq.append(value)
        return aub, bub, aeq, beq

    while free:
        width = n + 1
        aub, bub, aeq, beq = base(width)
        for player in free:
            row = [F(0)] * width
            row[player], row[n] = ((F(-1), F(1)) if mode == "min"
                                   else (F(1), F(-1)))
            aub.append(row); bub.append(F(0))
        objective = [F(0)] * width; objective[n] = F(-1 if mode == "min" else 1)
        status, objective_value, _ = exact_linprog(objective, aub, bub, aeq, beq)
        if status != "optimal":
            raise AssertionError(("selector stage failed", mode, status))
        level = -objective_value if mode == "min" else objective_value

        aub, bub, aeq, beq = base(width)
        for player in free:
            row = [F(0)] * width; row[player] = F(1)
            if mode == "min":
                row[player] = F(-1); bub.append(-level)
            else:
                bub.append(level)
            aub.append(row)
        newly = []
        for player in sorted(free):
            objective = [F(0)] * width; objective[player] = F(-1 if mode == "min" else 1)
            status, objective_value, _ = exact_linprog(objective, aub, bub, aeq, beq)
            if status != "optimal":
                raise AssertionError(("selector pin failed", mode, status))
            trial = -objective_value if mode == "min" else objective_value
            if trial == level:
                newly.append(player)
        if not newly:
            raise AssertionError(("selector stage pinned nobody", mode, level))
        for player in newly:
            pinned[player] = level; free.remove(player)
    return tuple(pinned[i] for i in range(n))


def selectors(values, n):
    full = (1 << n) - 1; total = values[full]
    constraints = {mask: values[mask] for mask in range(1, full) if values[mask]}
    return (selector_from_constraints(constraints, n, total, "min"),
            selector_from_constraints(constraints, n, total, "max"))


def selector_pair(constraints, n, total):
    values = lower_envelope(constraints, n, total)
    return values, selector_from_constraints(constraints, n, total, "min"), \
        selector_from_constraints(constraints, n, total, "max")


def coalition_minimum_with_witness(constraints, n, total, coalition):
    aub, bub = [], []
    for row_mask, bound in constraints.items():
        if row_mask == (1 << n) - 1 or bound == 0:
            continue
        aub.append([-F((row_mask >> i) & 1) for i in range(n)])
        bub.append(-bound)
    for player in range(n):
        row = [F(0)] * n; row[player] = F(-1)
        aub.append(row); bub.append(F(0))
    objective = [F((coalition >> i) & 1) for i in range(n)]
    status, value, point = exact_linprog(
        objective, aub, bub, [[F(1)] * n], [total]
    )
    if status != "optimal":
        raise AssertionError(("coalition minimum failed", coalition, status))
    return value, tuple(point)


def coalition_minimum(constraints, n, total, coalition):
    return coalition_minimum_with_witness(constraints, n, total, coalition)[0]


def tight_rows(values, point):
    full = (1 << len(point)) - 1
    return tuple(mask for mask in range(1, full)
                 if csum(point, mask) == values[mask])


def solve_unique(matrix, rhs, width):
    aug = [list(map(F, row)) + [F(b)] for row, b in zip(matrix, rhs)]
    cursor = 0; pivots = []
    for column in range(width):
        pivot = next((r for r in range(cursor, len(aug)) if aug[r][column]), None)
        if pivot is None: continue
        aug[cursor], aug[pivot] = aug[pivot], aug[cursor]
        q = aug[cursor][column]; aug[cursor] = [v / q for v in aug[cursor]]
        for r in range(len(aug)):
            if r != cursor and aug[r][column]:
                q = aug[r][column]
                aug[r] = [a - q*b for a, b in zip(aug[r], aug[cursor])]
        pivots.append(column); cursor += 1
    if any(not any(row[:width]) and row[width] for row in aug): return None
    if len(pivots) != width: return None
    out = [F(0)] * width
    for r, column in enumerate(pivots): out[column] = aug[r][width]
    return tuple(out)


def matrix_rank(matrix):
    work = [list(map(F, row)) for row in matrix]
    rank = 0
    width = len(work[0]) if work else 0
    for column in range(width):
        pivot = next((r for r in range(rank, len(work)) if work[r][column]), None)
        if pivot is None: continue
        work[rank], work[pivot] = work[pivot], work[rank]
        q = work[rank][column]
        work[rank] = [v / q for v in work[rank]]
        for r in range(len(work)):
            if r != rank and work[r][column]:
                q = work[r][column]
                work[r] = [a - q*b for a, b in zip(work[r], work[rank])]
        rank += 1
    return rank


def normalized_cover(rows, top, n):
    matrix, rhs = [], []
    outsiders = tuple(i for i in range(n) if i not in top)
    for i in outsiders:
        matrix.append([*(F((row >> i) & 1) for row in rows), F(-1)])
        rhs.append(F(0))
    matrix.append([
        *(F(((row >> top[0]) & 1) + ((row >> top[1]) & 1)) for row in rows),
        F(-2),
    ]); rhs.append(F(1))
    solution = solve_unique(matrix, rhs, len(rows) + 1)
    if solution is None: return None
    weights, eta = solution[:-1], solution[-1]
    if min(weights) <= 0 or eta < 0: return None
    loads = tuple(sum((w for w, row in zip(weights, rows) if row >> i & 1), F(0))
                  for i in range(n))
    alpha = (loads[top[0]] - eta, loads[top[1]] - eta)
    if min(alpha) <= 0 or sum(alpha, F(0)) != 1: return None
    expected = tuple(eta + (alpha[top.index(i)] if i in top else 0) for i in range(n))
    if loads != expected: raise AssertionError((rows, loads, expected))
    return weights, eta, alpha


def covers(values, z):
    n = len(z); top = tuple(i for i, q in enumerate(z) if q == max(z))
    if len(top) != 2: return ()
    tight = tight_rows(values, z); out = []
    for size in range(1, n - 1):
        for rows in itertools.combinations(tight, size):
            item = normalized_cover(rows, top, n)
            if item is not None: out.append((rows, item))
    return tuple(out)


def canonical_cx(values, x):
    support = set()
    for stage, block in enumerate(payoff_blocks(x, "min")):
        for player in block:
            support.update(stage_support(values, x, "min", stage, player))
    return tuple(sorted(support))


def complete_cx_subsets(values, x, pool_max):
    pool = tight_rows(values, x); n = len(x); total = sum(x, F(0))
    if len(pool) > pool_max: return pool, None
    answer = []
    for size in range(len(pool) + 1):
        for rows in itertools.combinations(pool, size):
            constraints = {row: csum(x, row) for row in rows}
            lx = selector_from_constraints(constraints, n, total, "min")
            if lx == x: answer.append(rows)
    return pool, tuple(answer)


def lift(values, x, z, cx, cover_rows, diagnose_singletons=False):
    n = len(x); total = sum(x, F(0))
    constraints = {row: csum(x, row) for row in cx}
    constraints.update({row: csum(z, row) for row in cover_rows})
    lx = selector_from_constraints(constraints, n, total, "min")
    lz = selector_from_constraints(constraints, n, total, "max")
    faithful = lx == x and lz == z
    singleton = None
    if diagnose_singletons or not faithful:
        singleton = all(
            coalition_minimum(constraints, n, total, 1 << i) == 0
            for i in range(n)
        )
    return faithful, lx, lz, singleton


def audit_game(label, values, x, z, pool_max, replay_exact=True):
    n = len(x); total = sum(x, F(0))
    if x == z: return None
    if any(values[1 << i] for i in range(n)): return None
    if len(tuple(i for i, q in enumerate(z) if q == max(z))) != 2: return None
    if replay_exact:
        constraints = {m: values[m] for m in range(1, (1 << n) - 1) if values[m]}
        replay, rx, rz = selector_pair(constraints, n, total)
        if replay != values or rx != x or rz != z:
            raise AssertionError(("exact-game replay failed", label))
    cs = covers(values, z)
    fixed = canonical_cx(values, x)
    pool, all_cx = complete_cx_subsets(values, x, pool_max)
    if not cs:
        return {
            "label": label, "n": n, "total": str(total),
            "x": list(map(str, x)), "z": list(map(str, z)),
            "tight_x_rows": list(pool), "canonical_cx": list(fixed),
            "cover_count": 0, "covers": [], "no_qualifying_cover": True,
            "fixed_faithful_cover_exists": False,
            "cx_subsets_exhausted": all_cx is not None,
            "complete_cx_count": None if all_cx is None else len(all_cx),
            "existential_cx_faithful": False,
            "universal_cx_faithful": False,
            "strong_fixed_cx_counterexample": True,
            "existential_cx_counterexample": True,
            "full_game_replayed": replay_exact,
            "pin": {
                "constraints": {str(m): str(values[m])
                                for m in range(1, (1 << n) - 1)},
                "all_coalition_values": list(map(str, values)),
                "covers": [],
                "independent_replay": (
                    "all coalition minima and both selectors recomputed from constraints"
                    if replay_exact else
                    "MISSING: source archive exactness/selectors used; witness requires independent replay"
                ),
            },
        }
    # The Cartesian Cx-by-cover interpretation is separately bounded; every
    # cover is still tested against the fixed canonical certificate below.
    if len(cs) > 10:
        all_cx = None
    fixed_results = []
    top = tuple(i for i, q in enumerate(z) if q == max(z))
    outsiders = tuple(i for i in range(n) if i not in top)
    for rows, cert in cs:
        _weights, eta, _alpha = cert
        incidence = [[F((row >> i) & 1) for row in rows] for i in outsiders]
        comparison_compatible = all(
            csum(x, row) >= csum(z, row) for row in rows
        )
        if (eta > 0 and comparison_compatible
                and matrix_rank(incidence) == n - 2):
            # PXC97c: the cover equality pins both top coordinates, and full
            # outsider rank pins the rest.  Cx already preserves x.
            faithful, lx, lz, singleton = True, x, z, True
        else:
            faithful, lx, lz, singleton = lift(values, x, z, fixed, rows)
        fixed_results.append((faithful, rows, cert, lx, lz, singleton))
    result = {
        "label": label, "n": n, "total": str(total),
        "x": list(map(str, x)), "z": list(map(str, z)),
        "tight_x_rows": list(pool), "canonical_cx": list(fixed),
        "cover_count": len(cs),
        "covers": [
            {"index": index, "rows": list(q[1]),
             "weights": list(map(str, q[2][0])), "eta": str(q[2][1]),
             "alpha": list(map(str, q[2][2])), "fixed_faithful": q[0],
             "fixed_lmin": list(map(str, q[3])),
             "fixed_lmax": list(map(str, q[4])),
             "fixed_lift_singleton_normalized": q[5]}
            for index, q in enumerate(fixed_results)
        ],
        "fixed_faithful_cover_exists": any(q[0] for q in fixed_results),
        "cx_subsets_exhausted": all_cx is not None,
        "full_game_replayed": replay_exact,
    }
    if all_cx is not None:
        matrix = []
        for cx in all_cx:
            outcomes = [lift(values, x, z, cx, rows) for rows, _ in cs]
            matrix.append((cx, outcomes))
        result.update({
            "complete_cx_count": len(all_cx),
            "existential_cx_faithful": any(any(q[0] for q in outcomes)
                                             for _, outcomes in matrix),
            "universal_cx_faithful": all(any(q[0] for q in outcomes)
                                           for _, outcomes in matrix),
            "complete_cx_cover_matrix": [
                {"cx_rows": list(cx),
                 "faithful_cover_indices": [i for i, outcome in enumerate(outcomes)
                                             if outcome[0]]}
                for cx, outcomes in matrix
            ],
        })
    result["strong_fixed_cx_counterexample"] = (
        not result["fixed_faithful_cover_exists"]
        or (all_cx is not None and not result["universal_cx_faithful"])
    )
    result["existential_cx_counterexample"] = (
        all_cx is not None and not result["existential_cx_faithful"]
    )
    if result["strong_fixed_cx_counterexample"]:
        failing_cx = []
        if all_cx is not None:
            for cx, outcomes in matrix:
                if any(q[0] for q in outcomes):
                    continue
                failing_cx.append({
                    "cx_rows": list(cx),
                    "cover_lifts": [
                        {"cover_index": i, "lmin": list(map(str, q[1])),
                         "lmax": list(map(str, q[2])),
                         "singleton_normalized": q[3]}
                        for i, q in enumerate(outcomes)
                    ],
                })
        result["pin"] = {
            "constraints": {str(m): str(values[m]) for m in range(1, (1 << n) - 1)},
            "all_coalition_values": list(map(str, values)),
            "covers": [{"rows": list(rows), "weights": list(map(str, cert[0])),
                        "eta": str(cert[1]), "alpha": list(map(str, cert[2]))}
                       for rows, cert in cs],
            "fixed_lifts": [{"rows": list(q[1]), "lmin": list(map(str, q[3])),
                            "lmax": list(map(str, q[4])), "singleton": q[5]}
                            for q in fixed_results],
            "failing_complete_cx": failing_cx,
            "independent_replay": (
                "all coalition minima and both selectors recomputed from constraints"
                if replay_exact else
                "MISSING: source archive exactness/selectors used; witness requires independent replay"
            ),
        }
    return result


def exact_n6_counterexample():
    """Independently reconstruct and fail-closed audit the discovered game."""
    values, x, z = selector_pair(N6_COUNTEREXAMPLE_CONSTRAINTS, 6, F(17))
    if x != N6_COUNTEREXAMPLE_X or z != N6_COUNTEREXAMPLE_Z:
        raise AssertionError(("n6 counterexample selectors changed", x, z))
    if any(values[1 << i] != 0 for i in range(6)):
        raise AssertionError("n6 counterexample lost singleton normalization")
    if tight_rows(values, x) != (7, 11):
        raise AssertionError(("n6 counterexample x-tight pool changed", tight_rows(values, x)))
    if tight_rows(values, z) != (3, 7, 11, 17, 51):
        raise AssertionError(("n6 counterexample z-tight pool changed", tight_rows(values, z)))
    item = audit_game("unrestricted_n6_exact_counterexample", values, x, z, 63,
                      replay_exact=True)
    expected_cover_rows = [(3,), (7, 11, 51)]
    if ([tuple(q["rows"]) for q in item["covers"]] != expected_cover_rows
            or item["complete_cx_count"] != 1
            or item["complete_cx_cover_matrix"] != [
                {"cx_rows": [7, 11], "faithful_cover_indices": []}
            ]
            or not item["strong_fixed_cx_counterexample"]
            or not item["existential_cx_counterexample"]):
        raise AssertionError(("n6 counterexample census changed", item))
    if any(tuple(map(F, q["fixed_lmax"])) != N6_COUNTEREXAMPLE_REDUCED_Z
           for q in item["covers"]):
        raise AssertionError("n6 counterexample reduced Lmax changed")
    singleton_witnesses = []
    for player in range(6):
        value, point = coalition_minimum_with_witness(
            N6_COUNTEREXAMPLE_CONSTRAINTS, 6, F(17), 1 << player
        )
        if value != 0 or point[player] != 0:
            raise AssertionError(("bad singleton witness", player, value, point))
        singleton_witnesses.append({
            "player": player, "minimum": str(value),
            "core_allocation": list(map(str, point)),
        })
    item["pin"].update({
        "original_constraints": {str(m): str(q)
                                 for m, q in N6_COUNTEREXAMPLE_CONSTRAINTS.items()},
        "singleton_minimizer_witnesses": singleton_witnesses,
        "cover_extremality": [
            {"rows": q["rows"], "positive_weights": q["weights"],
             "eta": q["eta"], "positive_top_coefficients": q["alpha"],
             "normalized_system_rank": len(q["rows"]) + 1,
             "normalized_system_unknowns": len(q["rows"]) + 1,
             "unique_solution": True}
            for q in item["covers"]
        ],
    })
    return values, x, z, item


def compositions(total, n):
    if n == 1:
        yield (total,); return
    for q in range(total + 1):
        for tail in compositions(total - q, n - 1): yield (q,) + tail


def generator_games(n, total_max):
    seen = set()
    for total in range(1, total_max + 1):
        points = tuple(compositions(total, n))
        for i, g in enumerate(points):
            for h in points[i + 1:]:
                if any(g[j] and h[j] for j in range(n)): continue
                raw = tuple(min(csum(g, m), csum(h, m)) for m in range(1 << n))
                if raw in seen: continue
                seen.add(raw)
                x, z = selectors(raw, n)
                if len(tuple(i for i, q in enumerate(z) if q == max(z))) != 2:
                    continue
                constraints = {m: raw[m] for m in range(1, (1 << n) - 1) if raw[m]}
                values = lower_envelope(constraints, n, F(total))
                if values != raw: continue
                yield f"two_generator_n{n}_T{total}_{len(seen)}", values, x, z


