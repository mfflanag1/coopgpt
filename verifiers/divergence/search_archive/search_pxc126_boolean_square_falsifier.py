from verify_pxc121_obstruction_spectral_closure import (  # noqa: E402
    actual_top_bound,
    target_coefficient,
)


N = 6
TOP = (0, 1)
FULL = (1 << N) - 1
TOTAL = F(25)
BASE = {3: F(12), 19: F(14), 39: F(89, 5), 43: F(23)}
PXC127 = {
    3: F(12), 19: F(69, 5), 39: F(89, 5), 43: F(23), 55: F(99, 5)
}
SEED_X = (F(13, 2), F(13, 2), F(1), F(5), F(1), F(5))
SEED_Z = (F(6), F(6), F(0), F(26, 5), F(2), F(29, 5))


def positive(q):
    return max(F(0), q)


def square_max(x, z, top, common_rows, blockers):
    residual = tuple(i for i in range(len(x)) if i not in top)
    a = tuple(min(x[i], z[i]) for i in range(len(x)))
    b = tuple(max(x[i], z[i]) for i in range(len(x)))
    best = F(0)
    witness = None
    audited = 0
    for C in common_rows:
        for Q in blockers:
            cells = {
                (ec, eq): tuple(
                    i for i in residual
                    if ((C >> i) & 1, (Q >> i) & 1) == (ec, eq)
                )
                for ec in (0, 1) for eq in (0, 1)
            }
            if any(not cells[key] for key in cells):
                continue
            for u11 in cells[1, 1]:
                for u01 in cells[0, 1]:
                    for u10 in cells[1, 0]:
                        for u00 in cells[0, 0]:
                            audited += 1
                            price = positive(a[u11] - b[u01]) + positive(
                                a[u10] - b[u00]
                            )
                            if price > best:
                                best = price
                                witness = {
                                    "C": C,
                                    "Q": Q,
                                    "u11_u01_u10_u00": (u11, u01, u10, u00),
                                    "lengths": (
                                        positive(a[u11] - b[u01]),
                                        positive(a[u10] - b[u00]),
                                    ),
                                }
    return best, witness, audited


def cut_max(x, z, top, common_rows):
    """Best mixed-orientation matching price across one retained common row."""
    residual = tuple(i for i in range(len(x)) if i not in top)
    a = tuple(min(x[i], z[i]) for i in range(len(x)))
    b = tuple(max(x[i], z[i]) for i in range(len(x)))

    def orientation(high, low):
        high_values = sorted((a[i] for i in high), reverse=True)
        low_values = sorted(b[i] for i in low)
        lengths = tuple(positive(p - q) for p, q in zip(high_values, low_values))
        return sum(lengths, F(0)), lengths

    best = F(0)
    witness = None
    for C in common_rows:
        inside = tuple(i for i in residual if C >> i & 1)
        outside = tuple(i for i in residual if not (C >> i & 1))
        for orientation_name, high, low in (
            ("inside_to_outside", inside, outside),
            ("outside_to_inside", outside, inside),
        ):
            price, lengths = orientation(high, low)
            if price > best:
                best = price
                witness = {
                    "C": C,
                    "orientation": orientation_name,
                    "high": high,
                    "low": low,
                    "lengths": lengths,
                }
        for size in range(1, min(len(inside), len(outside)) + 1):
            for left in itertools.combinations(inside, size):
                for right in itertools.permutations(outside, size):
                    matching = tuple(zip(left, right))
                    lengths = tuple(max(
                        positive(a[i] - b[j]), positive(a[j] - b[i])
                    ) for i, j in matching)
                    price = sum(lengths, F(0))
                    if price > best:
                        best = price
                        witness = {
                            "C": C,
                            "orientation": "edgewise_mixed",
                            "matching": matching,
                            "lengths": lengths,
                        }
    return best, witness


def classify(label, constraints, require_candidate=False):
    values = lower_envelope(constraints, N, TOTAL)
    if any(values[1 << i] for i in range(N)):
        raise AssertionError((label, "lost singleton normalization"))
    x, z = selectors(values, N)
    top_value = max(z)
    top = tuple(i for i, q in enumerate(z) if q == top_value)
    if top != TOP or x == z:
        return None, "selector_filter"
    BH = actual_top_bound(x, z)
    target = target_coefficient(N) * TOTAL
    demand = target - BH
    if demand <= 0:
        return None, "nonpositive_demand"
    cx = canonical_cx(values, x)
    cs = covers(values, z)
    if not cs or len(cs) > 40:
        return None, "cover_filter"
    instance = {
        "label": label,
        "x": x,
        "z": z,
        "top": top,
        "cx": cx,
        "covers": [
            {"rows": rows, "weights": cert[0], "eta": cert[1], "alpha": cert[2]}
            for rows, cert in cs
        ],
    }
    verdict = recognize(instance)
    if verdict["classification"] != "common-direction forced-zero":
        return None, "not_common"
    union = tuple(verdict["cover_union"])
    common_slots = tuple(all_descent_slots(instance, union))
    ztight = tight_rows(values, z)
    blockers = tuple(sorted({
        Q for _stage, _designated, d in common_slots
        for Q in ztight if Q not in union and csum(d, Q) < 0
    }))
    if not blockers:
        raise AssertionError((label, "PXC103 blocker missing"))
    common_rows = tuple(C for C in cx if csum(x, C) == csum(z, C))
    best, square_witness, audited = square_max(
        x, z, top, common_rows, blockers
    )
    cut, cut_witness = cut_max(x, z, top, common_rows)
    item = {
        "label": label,
        "constraints": constraints,
        "all_coalition_values": values,
        "x": x,
        "z": z,
        "actual_top_bound": BH,
        "target": target,
        "demand": demand,
        "canonical_cx": cx,
        "common_cx_rows": common_rows,
        "proper_z_tight_rows": ztight,
        "covers": instance["covers"],
        "cover_union": union,
        "common_descent_slots": tuple(
            {"stage": stage, "designated": designated, "direction": d}
            for stage, designated, d in common_slots
        ),
        "outside_union_negative_blockers": blockers,
        "boolean_square_choices_audited": audited,
        "maximum_boolean_square": best,
        "maximum_square_witness": square_witness,
        "square_gap": best - demand,
        "square_only_falsifier_candidate": best < demand,
        "maximum_common_row_cut": cut,
        "maximum_cut_witness": cut_witness,
        "cut_gap": cut - demand,
        "cut_only_falsifier_candidate": cut < demand,
    }
    if require_candidate and not item["square_only_falsifier_candidate"]:
        raise AssertionError((label, "calibration should not be a falsifier", item))
    return item, "common_positive"


def mutated_constraints(rng, round_index, mode):
    constraints = {}
    if mode == "local" or round_index % 2 == 0:
        # Stay inside or close to the open PXC125 chamber often enough to
        # exercise the full common-positive gate.  An optional fifth row is
        # placed near its seed comparison boundary to seek a genuinely new
        # blocker/certificate incidence rather than only retesting four RHSs.
        constraints = {
            mask: min(TOTAL, max(F(0), bound + F(rng.randint(-1, 1), 5)))
            for mask, bound in BASE.items()
        }
        if rng.random() < 0.7:
            trace = rng.randrange(1, 16)
            mask = 3 | (trace << 2)
            boundary = min(csum(SEED_X, mask), csum(SEED_Z, mask))
            constraints[mask] = min(
                TOTAL, max(F(0), boundary + F(rng.randint(-2, 2), 5))
            )
        return constraints
    # Mutate or occasionally delete the three non-pair base rows.  Keep rh so
    # the first ceiling has a stable exact calibration, but allow its level to
    # move.  All bounds remain feasible because every row contains r,h.
    for mask, bound in BASE.items():
        if mask != 3 and rng.random() < 0.12:
            continue
        shift = F(rng.randint(-30, 30), 5)
        constraints[mask] = min(TOTAL, max(F(0), bound + shift))
    for _ in range(rng.randint(0, 4)):
        trace = rng.randrange(1, 16)
        mask = 3 | (trace << 2)
        constraints[mask] = F(rng.randint(0, 125), 5)
    return constraints


def stringify(value):
    if isinstance(value, F):
        return str(value)
    if isinstance(value, tuple):
        return [stringify(item) for item in value]
    if isinstance(value, list):
        return [stringify(item) for item in value]
    if isinstance(value, dict):
        return {str(key): stringify(item) for key, item in value.items()}
    return value


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rounds", type=int, default=500)
    parser.add_argument("--seed", type=int, default=20260823)
    parser.add_argument("--mode", choices=("mixed", "local"), default="mixed")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()

    calibration, status = classify("PXC122_t1", BASE)
    if status != "common_positive" or calibration is None:
        raise AssertionError(("PXC122 calibration not reached", status))
    if (
        calibration["demand"] != F(2, 3)
        or calibration["maximum_boolean_square"] != F(7)
        or calibration["square_only_falsifier_candidate"]
    ):
        raise AssertionError(("PXC122 calibration changed", calibration))
    square_falsifier, status = classify(
        "PXC127_square_falsifier", PXC127, require_candidate=True
    )
    if status != "common_positive" or square_falsifier is None:
        raise AssertionError(("PXC127 calibration not reached", status))
    if (
        square_falsifier["demand"] != F(2, 3)
        or square_falsifier["maximum_boolean_square"] != 0
        or square_falsifier["maximum_common_row_cut"] != F(37, 5)
        or not square_falsifier["square_only_falsifier_candidate"]
        or square_falsifier["cut_only_falsifier_candidate"]
    ):
        raise AssertionError(("PXC127 calibration changed", square_falsifier))

    rng = random.Random(args.seed)
    counts = {
        "selector_filter": 0,
        "nonpositive_demand": 0,
        "cover_filter": 0,
        "not_common": 0,
        "common_positive": 0,
    }
    candidates = []
    closest = []
    for round_index in range(args.rounds):
        constraints = mutated_constraints(rng, round_index, args.mode)
        item, status = classify(f"mutation_{round_index}", constraints)
        counts[status] += 1
        if item is None:
            continue
        closest.append(item)
        closest.sort(key=lambda q: (q["square_gap"], q["label"]))
        del closest[10:]
        if item["square_only_falsifier_candidate"]:
            candidates.append(item)

    payload = {
        "claim": (
            "targeted exact search for PXC126 square-only and PXC127 "
            "common-row-cut falsifiers"
        ),
        "parameters": {
            "rounds": args.rounds, "seed": args.seed, "mode": args.mode
        },
        "calibration": calibration,
        "square_falsifier_cut_calibration": square_falsifier,
        "counts": counts,
        "candidates": candidates,
        "cut_falsifier_candidates": [
            item for item in candidates if item["cut_only_falsifier_candidate"]
        ],
        "closest_common_positive_records": closest,
        "scope": (
            "exact singleton-normalized six-player lower envelopes whose displayed "
            "rows all contain the symmetric top pair; a candidate falsifies only "
            "PXC126 square extraction, or the stronger PXC127 cut extraction when "
            "maximum_common_row_cut<D_H, until independently replayed and tested "
            "against the mixed singleton-witness projection; a null run is not a theorem"
        ),
    }
    rendered = json.dumps(stringify(payload), indent=2) + "\n"
    if args.output:
        args.output.write_text(rendered)
    print(rendered, end="")


if __name__ == "__main__":
    main()
