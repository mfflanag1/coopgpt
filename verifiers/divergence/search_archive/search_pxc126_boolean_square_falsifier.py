#!/usr/bin/env python3
"""Targeted exact search for PXC126 square and PXC127 cut extraction.

This is not a catalogue of six-player primitives.  It searches one broad
lower-envelope class in which every defining row contains the two symmetric
top labels.  The all-root and all-other-top allocations make every generated
game singleton-normalized, while lower-envelope construction makes it exact.

A retained record must have positive actual-top demand, universal failure of
all extreme covers for the canonical complete Cx, a PXC114 common descent,
and every Boolean square generated by every common Cx row and every negative
z-tight outside-union blocker strictly below the demand.  The blocker set is
a superset of blockers occurring in basic staged certificates, so a hit is a
valid square-only falsifier candidate.  The same records are then tested
against the stronger common-row cut price exposed by PXC127.  A cut-only hit
still needs independent replay and mixed-witness testing before promotion.
"""
