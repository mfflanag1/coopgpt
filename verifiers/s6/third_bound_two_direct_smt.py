#!/usr/bin/env python3
"""Emit a third, text-only formulation of the coefficient-two cases.

This generator imports only the Python standard library.  It imports neither
existing encoder and does not construct a Z3 AST.  The sole shared theorem
data are the frozen retained direction menus.

Activation is formulated by strict separation of the positive and negative
supports: on the Lmin side some positive-support payoff is below every
negative-support payoff; on the Lmax side some negative-support payoff is
above every positive-support payoff.  Coalitions are generated by cardinality
combinations and SMT-LIB is serialized directly as text.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from itertools import combinations
from pathlib import Path


HERE = Path(__file__).resolve().parent
CASES = {"p2_n3_t1": (2, 3, 1, 14), "p3_n3_t0": (3, 3, 0, 71)}


def form(operator, *arguments):
    return f"({operator} {' '.join(arguments)})"


def conjunction(arguments):
    arguments = tuple(arguments)
    if not arguments:
        return "true"
    if len(arguments) == 1:
        return arguments[0]
    return form("and", *arguments)


def disjunction(arguments):
    arguments = tuple(arguments)
    if not arguments:
        return "false"
    if len(arguments) == 1:
        return arguments[0]
    return form("or", *arguments)


def sum_expression(variables, players=None):
    terms = tuple(variables if players is None else (variables[player] for player in players))
    if not terms:
        return "0"
    if len(terms) == 1:
        return terms[0]
    return form("+", *terms)


def variables(case):
    x = tuple(f"tri_{case}_x_{player}" for player in range(6))
    z = tuple(f"tri_{case}_z_{player}" for player in range(6))
    q = tuple(
        tuple(f"tri_{case}_q_{anchor}_{player}" for player in range(6))
        for anchor in range(6)
    )
    return x, z, q


def load_menu(case):
    payload = json.loads((HERE / "strict_exchange_direction_cores.json").read_text())
    row = next(item for item in payload["rows"] if item["case"] == case)
    menu = tuple(
        (item["side"], tuple(int(value) for value in item["direction"]))
        for item in row["retained_menu"]
    )
    expected = CASES[case][3]
    if len(menu) != expected or len(set(menu)) != expected:
        raise AssertionError(f"{case}: retained menu changed")
    for side, direction in menu:
        if side not in ("min", "max") or len(direction) != 6:
            raise AssertionError((side, direction))
        if sum(direction) != 0 or not any(direction) or max(map(abs, direction)) > 2:
            raise AssertionError(direction)
    return menu


def support_separation(point, direction, side, nonstrict=False):
    positive = tuple(player for player, value in enumerate(direction) if value > 0)
    negative = tuple(player for player, value in enumerate(direction) if value < 0)
    if not positive or not negative:
        raise AssertionError(direction)
    if side == "min":
        relation = "<=" if nonstrict else "<"
        return disjunction(
            conjunction(form(relation, point[recipient], point[donor]) for donor in negative)
            for recipient in positive
        )
    if side == "max":
        relation = ">=" if nonstrict else ">"
        return disjunction(
            conjunction(form(relation, point[donor], point[recipient]) for recipient in positive)
            for donor in negative
        )
    raise ValueError(side)


def negative_cuts(direction):
    return tuple(
        coalition
        for size in range(1, 6)
        for coalition in combinations(range(6), size)
        if sum(direction[player] for player in coalition) < 0
    )


def blocker_disjunction(x, z, witnesses, direction, side, drop_first_cut=False):
    selected = x if side == "min" else z
    opposite = z if side == "min" else x
    cuts = negative_cuts(direction)
    if drop_first_cut:
        cuts = cuts[1:]
    alternatives = []
    for coalition in cuts:
        selected_sum = sum_expression(selected, coalition)
        alternatives.append(
            conjunction(
                (
                    form(">=", sum_expression(opposite, coalition), selected_sum),
                    *(
                        form(">=", sum_expression(witness, coalition), selected_sum)
                        for witness in witnesses
                    ),
                )
            )
        )
    if not alternatives:
        raise AssertionError("empty blocker disjunction")
    return disjunction(alternatives)


def base_assertions(case):
    positive_count, negative_count, tie_count, _ = CASES[case]
    x, z, witnesses = variables(case)
    positive = range(positive_count)
    negative = range(positive_count, positive_count + negative_count)
    tied = range(positive_count + negative_count, 6)
    assertions = [form("=", sum_expression(x), "1"), form("=", sum_expression(z), "1")]
    assertions.extend(form(">=", coordinate, "0") for coordinate in (*x, *z))
    assertions.extend(form(">", x[player], z[player]) for player in positive)
    assertions.extend(form(">", z[player], x[player]) for player in negative)
    assertions.extend(form("=", x[player], z[player]) for player in tied)
    positive_gap = sum_expression(
        tuple(form("-", x[player], z[player]) for player in positive)
    )
    assertions.append(form(">", form("*", "2", positive_gap), form("/", "2", "3")))

    # No unique maximum: every coordinate is weakly dominated by another.
    assertions.append(
        conjunction(
            disjunction(form(">=", z[other], z[player]) for other in range(6) if other != player)
            for player in range(6)
        )
    )
    assertions.append(
        disjunction(
            conjunction(
                (*[form(">=", z[player], z[other]) for other in range(6)],
                 form(">=", x[player], z[player]))
            )
            for player in range(6)
        )
    )
    assertions.append(
        disjunction(
            conjunction(
                (*[form("<=", x[player], x[other]) for other in range(6)],
                 form("<=", z[player], x[player]))
            )
            for player in range(6)
        )
    )
    for anchor, witness in enumerate(witnesses):
        assertions.extend(
            (
                form("=", sum_expression(witness), "1"),
                form("=", witness[anchor], "0"),
                *(form(">=", coordinate, "0") for coordinate in witness),
            )
        )
    if len(assertions) != 72:
        raise AssertionError(f"{case}: third base has {len(assertions)} assertions")
    return assertions


def case_assertions(case, nonstrict_activation=False, drop_first_cut=False):
    x, z, witnesses = variables(case)
    assertions = base_assertions(case)
    metadata = []
    for side, direction in load_menu(case):
        point = x if side == "min" else z
        cuts = negative_cuts(direction)
        assertions.append(
            form(
                "=>",
                support_separation(point, direction, side, nonstrict_activation),
                blocker_disjunction(x, z, witnesses, direction, side, drop_first_cut),
            )
        )
        metadata.append(
            {
                "side": side,
                "direction": list(direction),
                "negative_cut_count": len(cuts),
                "comparison_count": 7 * len(cuts),
            }
        )
    return assertions, metadata


def render_case(case, nonstrict_activation=False, drop_first_cut=False):
    x, z, witnesses = variables(case)
    names = (*x, *z, *(coordinate for witness in witnesses for coordinate in witness))
    assertions, metadata = case_assertions(case, nonstrict_activation, drop_first_cut)
    lines = ["(set-logic QF_LRA)"]
    lines.extend(f"(declare-fun {name} () Real)" for name in names)
    lines.extend(f"(assert {assertion})" for assertion in assertions)
    lines.append("(check-sat)")
    return "\n".join(lines) + "\n", metadata


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=HERE / "third_bound_two")
    parser.add_argument("--nonstrict-activation", action="store_true")
    parser.add_argument("--drop-first-cut", action="store_true")
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    for case in CASES:
        rendered, metadata = render_case(
            case, args.nonstrict_activation, args.drop_first_cut
        )
        target = args.output_dir / f"{case}.smt2"
        target.write_text(rendered)
        rows.append(
            {
                "case": case,
                "base_assertion_count": 72,
                "direction_implication_count": len(metadata),
                "negative_cut_count": sum(row["negative_cut_count"] for row in metadata),
                "comparison_count": sum(row["comparison_count"] for row in metadata),
                "formula_bytes": len(rendered.encode()),
                "formula_sha256": hashlib.sha256(rendered.encode()).hexdigest(),
            }
        )
    report = {
        "schema": "third-bound-two-direct-smt-v1",
        "status": "PASS",
        "independence": (
            "standard-library text generator; imports neither encoder nor Z3; "
            "shares only frozen retained direction menus"
        ),
        "activation": "strict separation of positive and negative payoff supports",
        "coalitions": "cardinality combinations of nonempty proper subsets",
        "mutations": {
            "nonstrict_activation": args.nonstrict_activation,
            "drop_first_cut": args.drop_first_cut,
        },
        "rows": rows,
    }
    (args.output_dir / "audit.json").write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n"
    )
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
