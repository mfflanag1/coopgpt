"""Seal the bounded campaign at or after its fixed deadline, then verify the ZIP."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    campaign_path = ROOT / "CAMPAIGN.json"
    campaign = json.loads(campaign_path.read_text())
    now = datetime.now(timezone.utc)
    deadline = datetime.fromisoformat(campaign["deadline_utc"])
    if now < deadline:
        raise SystemExit("The fixed 90-minute window has not ended.")
    start = datetime.fromisoformat(campaign["start_utc"])
    replay = json.loads((ROOT / "EXACT_REPLAY.json").read_text())
    portable = json.loads((ROOT / "PORTABILITY_CHECK.json").read_text())
    assert len(replay["checks"]) == len(portable["checks"]) == 12
    assert all(x["returncode"] == 0 for x in replay["checks"])
    assert all(x["returncode"] == 0 for x in portable["checks"])
    campaign.update({
        "status": "completed",
        "completed_utc": now.isoformat(),
        "elapsed_seconds": (now - start).total_seconds(),
        "gate_outcome": "STOP: no improved unrestricted upper bound or demonstrated subquadratic consequence",
        "frontier_unchanged": "sqrt(s/6) <= K_3(s) <= K_3^OUT(s) <= 3s^2",
        "evidence": "12 exact replay groups passed, including independent-directory portability replay; six opposite-model snapshot reviews adjudicated locally",
        "continuation": "No automatic extension. Specialist-review preparation remains the publication priority.",
    })
    campaign_path.write_text(json.dumps(campaign, indent=2) + "\n")
    report_path = ROOT / "CAMPAIGN_REPORT.txt"
    report = report_path.read_text().replace(
        "Draft synthesis; final timing and disposition recorded in CAMPAIGN.json.",
        "Final report. The fixed 90-minute window is complete; timing is recorded in CAMPAIGN.json.",
    )
    report_path.write_text(report)
    with (ROOT / "root/VERIFICATION_LOG.txt").open("a") as stream:
        stream.write(
            f"\nFINAL DISPOSITION {now.isoformat()}\n"
            f"Elapsed wall time: {(now-start).total_seconds():.3f} seconds.\n"
            "The 12 exact replay groups also passed from a clean independent directory.\n"
            "No general upper-bound improvement; stop at the fixed gate.\n"
            "No canonical manuscript edit, human outreach, or Git operation in this lane.\n"
        )
    files = sorted(
        p for p in ROOT.rglob("*")
        if p.is_file() and not p.is_symlink()
        and "__pycache__" not in p.parts
        and p.suffix not in {".pyc", ".zip"}
        and p.name != "FINAL_MANIFEST.json"
    )
    manifest = {
        "utc": now.isoformat(),
        "scope": "Every bundled file except this manifest; no generated bytecode",
        "file_count": len(files),
        "files": {str(p.relative_to(ROOT)): {"bytes": p.stat().st_size, "sha256": sha(p.read_bytes())} for p in files},
    }
    manifest_path = ROOT / "FINAL_MANIFEST.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    archive = ROOT.parent / "coopgpt-upper-bound-gate-2026-10-20.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for path in files + [manifest_path]:
            bundle.write(path, str(Path(ROOT.name) / path.relative_to(ROOT)))
    with zipfile.ZipFile(archive) as bundle:
        assert bundle.testzip() is None
        for relative, metadata in manifest["files"].items():
            data = bundle.read(str(Path(ROOT.name) / relative))
            assert len(data) == metadata["bytes"]
            assert sha(data) == metadata["sha256"]
    print(json.dumps({"archive": str(archive), "bytes": archive.stat().st_size,
                      "sha256": sha(archive.read_bytes()), "verified_files": len(files),
                      "elapsed_seconds": campaign["elapsed_seconds"]}, indent=2))


if __name__ == "__main__":
    main()
